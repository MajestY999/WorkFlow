import { Pool } from "pg";
import type { PoolClient, QueryResultRow as PgQueryResultRow } from "pg";

const schema = `
CREATE TABLE IF NOT EXISTS customers (
  id BIGSERIAL PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS categories (
  id BIGSERIAL PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS users (
  id BIGSERIAL PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('Client', 'Operator', 'Agent', 'Admin')),
  customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version INTEGER NOT NULL DEFAULT 1,
  title TEXT NOT NULL,
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  requester_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  assignee_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  status TEXT NOT NULL CHECK (status IN ('Новая', 'Назначена', 'Ожидает ответа', 'Решена')),
  priority TEXT NOT NULL CHECK (priority IN ('Низкий', 'Обычный', 'Высокий', 'Критический')),
  category_id BIGINT NOT NULL REFERENCES categories(id),
  created_at TEXT NOT NULL,
  due_at TEXT NOT NULL,
  description TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS request_comments (
  id BIGSERIAL PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  author_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  author_name TEXT NOT NULL,
  body TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 2000),
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS request_timeline (
  id BIGSERIAL PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  message TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS auth_sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS requests_customer_idx ON requests(customer_id);
CREATE INDEX IF NOT EXISTS requests_requester_idx ON requests(requester_user_id);
CREATE INDEX IF NOT EXISTS requests_assignee_idx ON requests(assignee_id);
CREATE INDEX IF NOT EXISTS request_comments_request_idx ON request_comments(request_id, id);
CREATE INDEX IF NOT EXISTS request_timeline_request_idx ON request_timeline(request_id, id);
CREATE INDEX IF NOT EXISTS auth_sessions_expiry_idx ON auth_sessions(expires_at);
`;

let pool: Pool | undefined;
let schemaReady: Promise<void> | undefined;

function getPool() {
  if (pool) return pool;
  const connectionString =
    process.env.NUXT_DATABASE_URL || process.env.DATABASE_URL;
  if (!connectionString) {
    throw new Error("NUXT_DATABASE_URL is required to connect to PostgreSQL.");
  }
  pool = new Pool({
    connectionString: String(connectionString),
    max: 10,
    idleTimeoutMillis: 30_000,
    connectionTimeoutMillis: 5_000,
  });
  return pool;
}

export async function ensureDatabase() {
  if (!schemaReady) {
    schemaReady = getPool()
      .query(schema)
      .then(() => undefined)
      .catch((error: unknown) => {
        schemaReady = undefined;
        throw error;
      });
  }
  await schemaReady;
}

export async function query<T extends PgQueryResultRow = PgQueryResultRow>(
  text: string,
  values: readonly unknown[] = [],
) {
  await ensureDatabase();
  return getPool().query<T>(text, [...values]);
}

export async function withTransaction<T>(
  callback: (client: PoolClient) => Promise<T>,
) {
  await ensureDatabase();
  const client = await getPool().connect();
  try {
    await client.query("BEGIN");
    const result = await callback(client);
    await client.query("COMMIT");
    return result;
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}

export type QueryResultRow = PgQueryResultRow;
